"""Build the three custom Agent presets from one capability definition."""
import argparse
import importlib.util
from pathlib import Path

INTEGRATIONS = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('spatialforge_preset_definition',
                                             INTEGRATIONS / 'spatialforge/preset_definition.py')
spatial = importlib.util.module_from_spec(spec)
spec.loader.exec_module(spatial)
base, yaml = spatial.base, spatial.yaml


def build(sources, dsh_root, python, config_path, service_config, *, package_imports=False):
    first = base.build(sources, dsh_root, python, config_path, package_imports=package_imports)
    headless = spatial.build(sources, dsh_root, python, service_config, config_path=config_path,
                             with_ui=False, package_imports=package_imports)
    workbench = spatial.build(sources, dsh_root, python, service_config, config_path=config_path,
                              with_ui=True, package_imports=package_imports)
    return [{'insert': [row for result in (first, headless, workbench)
                        for patch in result for row in patch['insert']]}]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    base.add_source_arguments(parser)
    parser.add_argument('--python', default='python3')
    parser.add_argument('--config', type=Path, default=Path('config/benchforge.local.json'))
    parser.add_argument('--service-config', type=Path, default=Path('config/spatialforge.local.json'))
    parser.add_argument('--package-imports', action='store_true', help='Use portable public package entrypoints')
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    sources = base.load_sources(args.dsh_root, args.node, args.dsh_resolve_from)
    result = build(sources, args.dsh_root, args.python, args.config, args.service_config,
                   package_imports=args.package_imports)
    args.output.write_text('# Generated by integrations/dsh/build_presets.py; edit the builders.\n'
                           + yaml.dump(result, Dumper=base.Dumper, sort_keys=False, allow_unicode=True),
                           encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
