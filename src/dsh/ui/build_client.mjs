import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';

const directory = path.dirname(fileURLToPath(import.meta.url));
const dsh = path.resolve(directory, '..');
const repository = path.resolve(dsh, '../..');
const require = createRequire(path.join(dsh, 'package.json'));
const {build} = require('esbuild');

await build({
  absWorkingDir: repository,
  entryPoints: [path.join(dsh, 'host/workbench/remote.ts')],
  outfile: path.join(dsh, 'host/workbench/remote.js'),
  platform: 'node',
  format: 'esm',
  target: ['es2022'],
  banner: {js: '/* @auto-generated from host/workbench/remote.ts. */'},
});

await build({
  absWorkingDir: repository,
  entryPoints: [path.join(directory, 'client/entry.js')],
  outfile: path.join(directory, 'client.js'),
  bundle: true,
  platform: 'browser',
  format: 'iife',
  target: ['es2022'],
  legalComments: 'none',
  banner: {js: '/* @auto-generated by src/dsh/ui/build_client.mjs; edit ui/client/ sources. */'},
});
