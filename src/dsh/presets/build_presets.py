"""Build the BenchForge Agent preset and its expandable workbench."""
import argparse
from pathlib import Path

if __package__:
    from dsh.presets import build_preset as base
    from dsh.presets import preset_definition as definition
else:
    import build_preset as base
    import preset_definition as definition

yaml = base.yaml


def build(standard, python, config_path, service_config, *, package_imports=False):
    entries = definition.build(standard, python, service_config, config_path=config_path,
                               package_imports=package_imports)
    return [{'insert': entries},
            *([] if package_imports else base.model_patches(config_path))]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    base.add_source_arguments(parser)
    parser.add_argument('--python', default='python3')
    parser.add_argument('--config', type=Path, default=Path('config/benchforge.local.json'))
    parser.add_argument('--service-config', type=Path)
    parser.add_argument('--package-imports', action='store_true', help='Use portable public package entrypoints')
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    service_config = args.service_config or (
        base.DEFAULT_SERVICE_CONFIG if args.package_imports else base.default_service_config())
    # A portable package has no deployment config yet; a local overlay must.
    if not args.package_imports and not service_config.is_file():
        parser.error(f'BenchForge configuration not found: {service_config.resolve()}. '
                     'Run python benchforge_app.py init, or pass --service-config with the actual file path.')
    sources = base.load_sources(args.dsh_root, args.node, args.dsh_resolve_from)
    result = build(sources, args.python, args.config, service_config,
                   package_imports=args.package_imports)
    args.output.write_text('# Generated by src/dsh/presets/build_presets.py; edit the preset definition.\n'
                           + yaml.dump(result, Dumper=base.Dumper, sort_keys=False, allow_unicode=True),
                           encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
