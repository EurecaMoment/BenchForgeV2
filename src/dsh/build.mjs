import {execFileSync} from 'node:child_process';
import {cp, mkdir, mkdtemp, readFile, realpath, rm, writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {WorkspaceTypertGenerator, writePackageArtifacts} from '@deepseek-ai/dsh-typert-generator';

const dsh = path.dirname(fileURLToPath(import.meta.url));
const directory = path.join(dsh, 'ui');
const repository = path.resolve(dsh, '../..');
const contract = path.join(dsh, 'host/workbench/remote');
const require = createRequire(path.join(dsh, 'package.json'));
const {build} = require('esbuild');

const protocol = '@deepseek-ai/dsh-typert-protocol';
const stage = await mkdtemp(path.join(tmpdir(), 'benchforge-typert-'));
const packages = path.join(stage, 'packages');
const workbench = path.join(packages, 'workbench');
const protocolRoot = path.join(packages, 'protocol');
const protocolTypes = './lib/types/index.d.ts';
const json = (file, value) => writeFile(file, JSON.stringify(value, null, 2));

try {
  // Typert discovers TypeScript projects from the Host workspace aggregate.
  // Stage this external package and the pinned protocol declarations for that pass.
  await mkdir(packages, {recursive: true});
  const protocolManifest = require.resolve(protocol + '/package.json');
  const protocolDirectory = path.dirname(protocolManifest);
  await cp(path.join(protocolDirectory, 'lib/types'), path.join(protocolRoot, 'lib/types'), {recursive: true});
  await cp(path.join(contract, 'src'), path.join(workbench, 'src'), {recursive: true});
  await cp(path.join(contract, 'package.json'), path.join(workbench, 'package.json'));
  await cp(path.join(contract, 'tsconfig.host.json'), path.join(workbench, 'tsconfig.host.json'));
  await json(path.join(protocolRoot, 'package.json'), {name: protocol, type: 'module', exports: {'.': protocolTypes}});
  await json(path.join(protocolRoot, 'tsconfig.json'), {files: [protocolTypes]});
  const options = JSON.parse(await readFile(path.join(contract, 'tsconfig.host.json'), 'utf8')).compilerOptions;
  await json(path.join(stage, 'tsconfig.host.json'), {
    files: [],
    compilerOptions: {
      target: options.target, module: options.module, strict: options.strict, skipLibCheck: options.skipLibCheck,
      paths: {
        [protocol]: ['./packages/protocol/lib/types/index.d.ts'],
        '@deepseek-ai/*': [path.join(dsh, 'node_modules/@deepseek-ai/*/lib/types/index.d.ts')],
      },
    },
    references: [{path: './packages/protocol'}, {path: './packages/workbench/tsconfig.host.json'}],
  });
  const name = JSON.parse(await readFile(path.join(contract, 'package.json'), 'utf8')).name;
  const artifacts = new WorkspaceTypertGenerator(stage, {checkDiagnostics: false}).generate([name], ['host']);
  writePackageArtifacts(contract, artifacts);
} finally {
  const stageRoot = await realpath(stage);
  if (path.dirname(stageRoot) !== await realpath(tmpdir()) ||
      !path.basename(stageRoot).startsWith('benchforge-typert-')) {
    throw new Error('Typert temporary directory is outside the build directory');
  }
  await rm(stageRoot, {recursive: true, force: true});
}

execFileSync(process.execPath, [require.resolve('typescript/bin/tsc'), '-p', path.join(contract, 'tsconfig.host.json')],
  {stdio: 'inherit'});

const clientName = JSON.stringify(JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8')).name);
await build({
  absWorkingDir: repository,
  entryPoints: [path.join(directory, 'client/entry.js')],
  outfile: path.join(directory, 'client.js'),
  bundle: true,
  external: ['zod'],
  platform: 'browser',
  format: 'iife',
  globalName: 'benchforgeClient',
  target: ['es2022'],
  legalComments: 'none',
  banner: {js: [
    '/* @auto-generated by src/dsh/build.mjs; edit ui/client/ sources. */',
    'window.__ModuleLoader__.load({',
    '  id: ' + clientName + ',',
    '  factory(require) {',
  ].join('\n')},
  footer: {js: '    return benchforgeClient.default(require);\n  },\n});'},
});
